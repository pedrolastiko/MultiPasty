import AppKit

/// Surveille le presse-papiers système par sondage du changeCount.
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private var timer: Timer?
    private var lastChangeCount: Int = NSPasteboard.general.changeCount
    /// changeCount à ignorer : celui que l'app vient elle-même de provoquer en recollant.
    private var ignoreChangeCount: Int = -1

    /// Types indiquant un contenu sensible (gestionnaires de mots de passe) : jamais enregistré.
    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType"
    ]

    private init() {}

    func start() {
        timer?.invalidate()
        let t = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in
            self?.poll()
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// À appeler juste après avoir écrit nous-mêmes dans le presse-papiers.
    func ignoreNextChange() {
        ignoreChangeCount = NSPasteboard.general.changeCount
        lastChangeCount = ignoreChangeCount
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        if pb.changeCount == ignoreChangeCount { return }

        // Contenu marqué confidentiel : on l'ignore volontairement.
        let types = Set((pb.types ?? []).map { $0.rawValue })
        if !types.isDisjoint(with: ClipboardMonitor.concealedTypes) { return }

        let sourceApp = NSWorkspace.shared.frontmostApplication?.localizedName

        if let string = pb.string(forType: .string), !string.isEmpty {
            HistoryStore.shared.addText(string, sourceApp: sourceApp)
            return
        }

        if types.contains(NSPasteboard.PasteboardType.tiff.rawValue)
            || types.contains(NSPasteboard.PasteboardType.png.rawValue) {
            if let image = NSImage(pasteboard: pb) {
                HistoryStore.shared.addImage(image, sourceApp: sourceApp)
            }
        }
    }

    /// Écrit l'élément dans le presse-papiers système.
    func write(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text, forType: .string)
        case .image:
            if let image = HistoryStore.shared.image(for: item) {
                pb.writeObjects([image])
            }
        }
        ignoreNextChange()
    }
}
